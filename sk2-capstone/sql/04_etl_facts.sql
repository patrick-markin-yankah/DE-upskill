-- MedInsure fact ETL (Deliverable 3 + DQ enforcement at load)
-- Prerequisites: 03_etl_dims.sql (dims populated)
-- Run: psql -h localhost -p 5432 -U postgres -d medinsure -f sql/04_etl_facts.sql
--
-- Patterns: high-water mark on processed_date, SCD inclusive-end lookups,
-- dead-letter + skip for:
--   unknown_member / unknown_provider / unknown_*_date
--   paid_exceeds_allowed  (total_paid > total_allowed * 1.05)
--   anachronistic_provider (service_date < network_effective_date)
--   orphan_procedure (claim line procedure not in dim_procedure)
-- SCD one-current checks remain post-load (Deliverable 6) for now.

\timing on
SET client_min_messages TO WARNING;
SET synchronous_commit TO OFF;
SET work_mem TO '512MB';
SET maintenance_work_mem TO '1GB';

-- ===========================================================================
-- Control + dead-letter infrastructure
-- ===========================================================================
CREATE TABLE IF NOT EXISTS dw.etl_control (
    table_name      TEXT PRIMARY KEY,
    high_water_mark DATE NOT NULL
);

INSERT INTO dw.etl_control (table_name, high_water_mark)
VALUES ('fact_claim', DATE '1900-01-01')
ON CONFLICT (table_name) DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.etl_run_log (
    run_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   TEXT NOT NULL,
    started_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at  TIMESTAMPTZ,
    rows_read    BIGINT,
    rows_loaded  BIGINT,
    rows_rejected BIGINT,
    status       TEXT NOT NULL DEFAULT 'running'
);

CREATE TABLE IF NOT EXISTS etl.dead_letter (
    dead_letter_id  BIGSERIAL PRIMARY KEY,
    rejected_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    source_table    TEXT NOT NULL,
    rule_violated   TEXT NOT NULL,
    raw_row         JSONB NOT NULL
);

-- ===========================================================================
-- fact_claim — incremental load (HWM on processed_date)
-- ===========================================================================
BEGIN;

INSERT INTO dw.etl_run_log (table_name) VALUES ('fact_claim');

CREATE TEMP TABLE tmp_new_claims ON COMMIT DROP AS
SELECT
    c.claim_id,
    c.member_id,
    c.provider_id,
    c.plan_id,
    c.service_date,
    c.processed_date,
    c.claim_type,
    c.claim_status,
    c.primary_diagnosis_code,
    c.total_allowed,
    c.total_paid
FROM public.claims c
JOIN dw.etl_control ctl
  ON ctl.table_name = 'fact_claim'
WHERE c.processed_date > ctl.high_water_mark;

CREATE TEMP TABLE tmp_claim_resolved ON COMMIT DROP AS
SELECT
    nc.*,
    ds.date_key AS service_date_key,
    dproc.date_key AS processed_date_key,
    dm.member_key,
    dp.provider_key,
    dp.network_effective_date,
    COALESCE(dd.diagnosis_key, 0) AS diagnosis_key,
    COALESCE(dpl.plan_key, 0)     AS plan_key,
    CASE
        WHEN dm.member_key IS NULL THEN 'unknown_member'
        WHEN dp.provider_key IS NULL THEN 'unknown_provider'
        WHEN ds.date_key IS NULL THEN 'unknown_service_date'
        WHEN dproc.date_key IS NULL THEN 'unknown_processed_date'
        WHEN nc.total_paid > nc.total_allowed * 1.05 THEN 'paid_exceeds_allowed'
        WHEN nc.service_date < dp.network_effective_date THEN 'anachronistic_provider'
        ELSE NULL
    END AS violation
FROM tmp_new_claims nc
LEFT JOIN dw.dim_date ds
       ON ds.full_date = nc.service_date
LEFT JOIN dw.dim_date dproc
       ON dproc.full_date = nc.processed_date
LEFT JOIN dw.dim_member dm
       ON dm.member_id = nc.member_id
      AND dm.member_key <> 0
      AND nc.service_date >= dm.effective_start
      AND nc.service_date <= dm.effective_end
LEFT JOIN dw.dim_provider dp
       ON dp.provider_id = nc.provider_id
      AND dp.provider_key <> 0
      AND nc.service_date >= dp.effective_start
      AND nc.service_date <= dp.effective_end
LEFT JOIN dw.dim_diagnosis dd
       ON dd.diagnosis_code = nc.primary_diagnosis_code
      AND dd.diagnosis_key <> 0
LEFT JOIN dw.dim_plan dpl
       ON dpl.plan_id = nc.plan_id
      AND dpl.plan_key <> 0;

INSERT INTO etl.dead_letter (source_table, rule_violated, raw_row)
SELECT
    'public.claims',
    violation,
    jsonb_build_object(
        'claim_id', claim_id,
        'member_id', member_id,
        'provider_id', provider_id,
        'service_date', service_date,
        'processed_date', processed_date,
        'primary_diagnosis_code', primary_diagnosis_code,
        'total_allowed', total_allowed,
        'total_paid', total_paid,
        'network_effective_date', network_effective_date
    )
FROM tmp_claim_resolved
WHERE violation IS NOT NULL;

INSERT INTO dw.fact_claim (
    claim_id, service_date_key, processed_date_key,
    member_key, provider_key, diagnosis_key, plan_key,
    claim_type, claim_status, total_allowed, total_paid
)
SELECT
    claim_id::int,
    service_date_key,
    processed_date_key,
    member_key,
    provider_key,
    diagnosis_key,
    plan_key,
    claim_type,
    claim_status,
    total_allowed,
    total_paid
FROM tmp_claim_resolved
WHERE violation IS NULL
ON CONFLICT (claim_id) DO NOTHING;

UPDATE dw.etl_run_log
SET finished_at   = clock_timestamp(),
    status        = 'success',
    rows_read     = (SELECT COUNT(*) FROM tmp_new_claims),
    rows_loaded   = (SELECT COUNT(*) FROM tmp_claim_resolved WHERE violation IS NULL),
    rows_rejected = (SELECT COUNT(*) FROM tmp_claim_resolved WHERE violation IS NOT NULL)
WHERE run_id = (SELECT MAX(run_id) FROM dw.etl_run_log WHERE table_name = 'fact_claim');

UPDATE dw.etl_control
SET high_water_mark = COALESCE(
        (SELECT MAX(processed_date) FROM public.claims),
        high_water_mark
    )
WHERE table_name = 'fact_claim';

COMMIT;

SELECT * FROM dw.etl_control WHERE table_name = 'fact_claim';
SELECT * FROM dw.etl_run_log WHERE table_name = 'fact_claim' ORDER BY run_id DESC LIMIT 1;
SELECT rule_violated, COUNT(*) AS n
FROM etl.dead_letter
WHERE source_table = 'public.claims'
GROUP BY rule_violated
ORDER BY 1;
SELECT COUNT(*) AS fact_claim_rows FROM dw.fact_claim;

-- ===========================================================================
-- fact_claim_line — after headers; dead-letter orphan procedures (no NA key)
-- ===========================================================================
BEGIN;

INSERT INTO dw.etl_run_log (table_name) VALUES ('fact_claim_line');

CREATE TEMP TABLE tmp_lines_resolved ON COMMIT DROP AS
SELECT
    cl.claim_line_id,
    cl.claim_id,
    cl.line_number,
    cl.procedure_code,
    cl.line_allowed,
    cl.line_paid,
    fc.claim_key,
    fc.service_date_key,
    fc.member_key,
    fc.provider_key,
    fc.plan_key,
    dpr.procedure_key,
    CASE
        WHEN fc.claim_key IS NULL THEN 'missing_claim_header'
        WHEN dpr.procedure_key IS NULL THEN 'orphan_procedure'
        ELSE NULL
    END AS violation
FROM public.claim_lines cl
LEFT JOIN dw.fact_claim fc
       ON fc.claim_id = cl.claim_id::int
LEFT JOIN dw.dim_procedure dpr
       ON dpr.procedure_code = cl.procedure_code
      AND dpr.procedure_key <> 0;

INSERT INTO etl.dead_letter (source_table, rule_violated, raw_row)
SELECT
    'public.claim_lines',
    violation,
    jsonb_build_object(
        'claim_line_id', claim_line_id,
        'claim_id', claim_id,
        'line_number', line_number,
        'procedure_code', procedure_code,
        'line_allowed', line_allowed,
        'line_paid', line_paid
    )
FROM tmp_lines_resolved
WHERE violation IS NOT NULL;

INSERT INTO dw.fact_claim_line (
    claim_line_id, claim_key, claim_id,
    service_date_key, member_key, provider_key, plan_key, procedure_key,
    line_number, line_allowed, line_paid
)
SELECT
    claim_line_id,
    claim_key,
    claim_id::int,
    service_date_key,
    member_key,
    provider_key,
    plan_key,
    procedure_key,
    line_number,
    line_allowed,
    line_paid
FROM tmp_lines_resolved
WHERE violation IS NULL
ON CONFLICT (claim_line_id) DO NOTHING;

UPDATE dw.etl_run_log
SET finished_at   = clock_timestamp(),
    status        = 'success',
    rows_read     = (SELECT COUNT(*) FROM tmp_lines_resolved),
    rows_loaded   = (SELECT COUNT(*) FROM tmp_lines_resolved WHERE violation IS NULL),
    rows_rejected = (SELECT COUNT(*) FROM tmp_lines_resolved WHERE violation IS NOT NULL)
WHERE run_id = (SELECT MAX(run_id) FROM dw.etl_run_log WHERE table_name = 'fact_claim_line');

COMMIT;

SELECT * FROM dw.etl_run_log WHERE table_name = 'fact_claim_line' ORDER BY run_id DESC LIMIT 1;
SELECT rule_violated, COUNT(*) AS n
FROM etl.dead_letter
WHERE source_table = 'public.claim_lines'
GROUP BY rule_violated
ORDER BY 1;
SELECT COUNT(*) AS fact_claim_line_rows FROM dw.fact_claim_line;

SELECT
    (SELECT COUNT(*) FROM public.claim_lines) AS oltp_lines,
    (SELECT COUNT(*) FROM dw.fact_claim_line) AS dw_lines,
    (SELECT COUNT(*) FROM etl.dead_letter WHERE source_table = 'public.claim_lines') AS lines_dead_lettered;

-- ===========================================================================
-- Idempotency proof — re-run header extract; should load 0 new rows
-- ===========================================================================
BEGIN;
INSERT INTO dw.etl_run_log (table_name) VALUES ('fact_claim_rerun');

WITH mark AS (
    SELECT high_water_mark FROM dw.etl_control WHERE table_name = 'fact_claim'
),
new_claims AS (
    SELECT COUNT(*) AS n
    FROM public.claims c
    CROSS JOIN mark m
    WHERE c.processed_date > m.high_water_mark
)
UPDATE dw.etl_run_log
SET finished_at = clock_timestamp(),
    status = 'success',
    rows_read = (SELECT n FROM new_claims),
    rows_loaded = 0,
    rows_rejected = 0
WHERE run_id = (SELECT MAX(run_id) FROM dw.etl_run_log WHERE table_name = 'fact_claim_rerun');

COMMIT;

SELECT 'incremental_rerun_new_claims' AS check_name,
       rows_read
FROM dw.etl_run_log
WHERE table_name = 'fact_claim_rerun'
ORDER BY run_id DESC
LIMIT 1;
